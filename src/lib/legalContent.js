export const legalFor = (lang) => LEGAL[(lang || "en").slice(0, 2)] || LEGAL.en

const STORAGE_KEY = "slipzo_policy_accepted"

export function hasAcceptedPolicy() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY) || "null")
    return Boolean(saved && saved.version === POLICY_VERSION)
  } catch {
    return false
  }
}

export function saveAcceptedPolicy() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify({ version: POLICY_VERSION, at: new Date().toISOString() }))
  } catch {
    // storage blocked: the screen will simply be shown again next time
  }
}
